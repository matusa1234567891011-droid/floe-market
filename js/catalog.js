function normalizeText(s) {
  return s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9]+/g, ' ').trim();
}

function slugify(s) {
  const map = { а:'a',б:'b',в:'v',г:'g',д:'d',е:'e',ё:'e',ж:'zh',з:'z',и:'i',й:'y',к:'k',л:'l',м:'m',н:'n',о:'o',п:'p',р:'r',с:'s',т:'t',у:'u',ф:'f',х:'h',ц:'c',ч:'ch',ш:'sh',щ:'sch',ы:'y',э:'e',ю:'yu',я:'ya' };
  return s.toLowerCase().split('').map(c => map[c] ?? c).join('').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

const CATALOG = RAW_CATALOG.map(([name, platforms, aliases, sections], index) => {
  const pl = platforms.split(' ');
  return {
    name,
    slug: slugify(name),
    platforms: pl,
    sections: sections || DEFAULT_SECTIONS[pl[0]],
    popular: index < 30,
    search: normalizeText(`${name} ${aliases}`),
  };
});
const CATALOG_BY_SLUG = Object.fromEntries(CATALOG.map(g => [g.slug, g]));
